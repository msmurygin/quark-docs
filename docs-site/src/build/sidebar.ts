import type {PluginOptions} from '@docusaurus/plugin-content-docs';

type SidebarItemsGeneratorOption = PluginOptions['sidebarItemsGenerator'];

/** Human names and order of the top-level parts of the guide. */
const PARTS: Array<{dir: string; label: string}> = [
  {dir: 'operator', label: 'Operator guide'},
  {dir: 'admin', label: 'Administrator guide'},
  {dir: 'reference', label: 'Screen reference'},
  {dir: 'diagrams', label: 'Diagrams'},
  {dir: 'studio', label: 'Metadata Studio'},
  {dir: 'api', label: 'API guide'},
];

type Item = Awaited<ReturnType<SidebarItemsGeneratorOption>>[number];

/**
 * Autogenerated from the folders, then tidied: fixed order, human category
 * names, each part's 00-README is the page the category title opens, and
 * author-only folders (assets/) never reach the sidebar.
 */
export const sidebarItemsGenerator: SidebarItemsGeneratorOption = async ({defaultSidebarItemsGenerator, ...args}) => {
  const items = (await defaultSidebarItemsGenerator({...args})) as Item[];
  if (args.item.dirName !== '.') return items;

  const rank = (it: Item): number => {
    if (it.type === 'doc') return -1; // "Getting started" first
    const dir = it.type === 'category' ? PARTS.findIndex((p) => it.label.toLowerCase().includes(p.dir)) : -1;
    return dir >= 0 ? dir : 99;
  };

  const out: Item[] = [];
  for (const it of items) {
    if (it.type !== 'category') {
      out.push(it);
      continue;
    }
    const part = PARTS.find((p) => it.items.some((c) => 'id' in c && typeof c.id === 'string' && c.id.startsWith(`${p.dir}/`)) || (it.link && 'id' in it.link && String(it.link.id).startsWith(`${p.dir}/`)));
    if (!part) continue; // assets/ and anything else author-only
    // The part's 00-README (labelled "Overview") opens when the title is clicked.
    const overview = it.items.find((c) => c.type === 'doc' && c.label === 'Overview');
    const rest = it.items.filter((c) => c !== overview);
    out.push({
      ...it,
      label: part.label,
      collapsed: true,
      collapsible: true,
      link: overview && overview.type === 'doc' ? {type: 'doc', id: overview.id} : it.link,
      items: rest,
    } as Item);
  }
  return out.sort((a, b) => rank(a) - rank(b));
};
